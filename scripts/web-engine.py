#!/usr/bin/env python3
"""Place the compiled wasm engine at a content-addressed path and emit its hash.

This runs BEFORE `astro build`, not after, which is the whole reason it is a
separate script. The module goes into `web/public/`, so Astro copies it into
`dist/` verbatim; and the constants it writes are TypeScript the build then
compiles into the bundle. Doing it afterwards would mean the hash the page
carries was not in the page the hash was computed over.

Two things it fixes that are easy to miss:

  * `WASM_URL` in `src/engine/abi.ts` is `/pochoir_core.wasm` — unhashed, and
    naming a crate that no longer exists; the artefact `make wasm` produces is
    `pochoir_wasm.wasm`.
    An unhashed URL reintroduces exactly the failure ADR-0004 Decision 5's
    second trap describes: mid-rollout, HTML from version N+1 carries an
    integrity hash while that URL still resolves to version N's bytes, and the
    fetch fails closed. The engine has to be content-addressed like everything
    else.
  * The module is placed under `_pochoir/engine/` so that `_headers` can set
    `Content-Type: application/wasm` with a trailing splat — the only pattern
    form Cloudflare documents — and
    `WebAssembly.instantiateStreaming` rejects any other type.

Usage:
  scripts/web-engine.py target/wasm32-unknown-unknown/release/pochoir_wasm.wasm
  scripts/web-engine.py --clear          remove a previously placed module

Standard library only. Exit 0 on success, 2 on usage.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import sys
from base64 import b64encode
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ENGINE_DIR = REPO / "web" / "public" / "_pochoir" / "engine"
CONSTANTS = REPO / "web" / "src" / "engine" / "wasm-build.ts"

# Long enough that a collision is not a thing to think about, short enough to
# read in a URL. Vite's own asset hashes are 8 characters; this is 16.
HASH_CHARS = 16

TEMPLATE = """// GENERATED by scripts/web-engine.py. Do not edit, and do not commit a stale
// copy: `make web-engine ENGINE=…` rewrites it from the artefact it places.
//
// ADR-0004 Decision 2: the engine is fetched with this hash as `integrity`, so
// the browser refuses the module before a byte reaches our code. ADR-0004
// Decision 4 item 4: the value is a build output, never hand-maintained — a
// stale hash fails closed and the application stops working.

/** Content-addressed, so an old page keeps resolving to the bytes it names. */
export const WASM_URL = {url};

/** SHA-384 of the bytes at WASM_URL, as the `integrity` option wants it. */
export const WASM_INTEGRITY: string | undefined = {integrity};
"""

ABSENT = """// GENERATED by scripts/web-engine.py. Do not edit.
//
// No engine has been placed in this build. `select.ts` returns the stub, so
// nothing reads these; they exist so the module always type-checks.

export const WASM_URL = '/pochoir_core.wasm';

export const WASM_INTEGRITY: string | undefined = undefined;
"""


def clear() -> int:
    if ENGINE_DIR.is_dir():
        shutil.rmtree(ENGINE_DIR)
        print(f"web-engine: removed {ENGINE_DIR.relative_to(REPO)}")
    CONSTANTS.parent.mkdir(parents=True, exist_ok=True)
    CONSTANTS.write_text(ABSENT, encoding="utf-8")
    print(f"web-engine: {CONSTANTS.relative_to(REPO)} reset to 'no engine'")
    return 0


def place(source: Path) -> int:
    if not source.is_file():
        print(f"web-engine: {source} does not exist", file=sys.stderr)
        return 2
    data = source.read_bytes()
    if data[:4] != b"\x00asm":
        print(
            f"web-engine: {source} does not start with the WebAssembly magic "
            f"(got {data[:4]!r}); refusing to place it",
            file=sys.stderr,
        )
        return 2

    digest = hashlib.sha384(data).digest()
    short = hashlib.sha256(data).hexdigest()[:HASH_CHARS]
    # Named after the artefact, not after a crate name hard-coded here: the
    # engine crate was `pochoir_core` when this was written and is
    # `pochoir_wasm` now, and the served path should follow the file.
    name = f"{source.stem}.{short}.wasm"

    # One module at a time. A stale module left beside a new one would still be
    # served to anyone holding an old HTML, which is the point of content
    # addressing — but it would also be a module nothing attests any more.
    if ENGINE_DIR.is_dir():
        shutil.rmtree(ENGINE_DIR)
    ENGINE_DIR.mkdir(parents=True)
    (ENGINE_DIR / name).write_bytes(data)

    url = f"/_pochoir/engine/{name}"
    integrity = f"sha384-{b64encode(digest).decode('ascii')}"
    CONSTANTS.parent.mkdir(parents=True, exist_ok=True)
    CONSTANTS.write_text(
        TEMPLATE.format(url=f"'{url}'", integrity=f"'{integrity}'"), encoding="utf-8"
    )

    print(f"web-engine: {len(data)} bytes -> web/public{url}")
    print(f"web-engine: {integrity}")
    print(f"web-engine: wrote {CONSTANTS.relative_to(REPO)}")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="web-engine.py")
    parser.add_argument("engine", nargs="?", type=Path)
    parser.add_argument("--clear", action="store_true")
    args = parser.parse_args(argv[1:])

    if args.clear:
        return clear()
    if args.engine is None:
        parser.print_usage(sys.stderr)
        return 2
    return place(args.engine)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
