#!/bin/sh
#
# Dependency guard. Run by `make deps-check`, and by CI via `make check`.
#
# This project is deliberately lean on dependencies: we would rather write a
# feature ourselves than inherit a crate we do not control, for reasons of
# supply-chain surface and client bundle size. ADR-0001 sharpens that into
# "hand-roll everything that writes; depend deliberately only for parsers of
# hostile input". This script makes the policy mechanical instead of
# aspirational.
#
# There are two checks, and they do different jobs.
#
#   1. GLOBAL COUNT — a blunt alarm. The number of [[package]] entries in
#      Cargo.lock against THRESHOLD. It is workspace-global, so it is blind to
#      *which* crate pulled something in, and once the PDF renderer of ADR-0003
#      arrives the number jumps to roughly 81 and stops protecting the core
#      module at all. It is kept because it is the only check that also sees
#      dev- and build-dependencies, which the per-crate check deliberately
#      excludes.
#
#   2. PER-CRATE ALLOWLIST — the real guard, as ADR-0001 and ADR-0003 require.
#      For each guarded crate, the set of third-party crates in its dependency
#      closure must match `scripts/allowlist/<crate>.txt` exactly. This is what
#      keeps `pochoir-core`'s closure a strict subset of the PDF module's: a
#      crate appearing in the core that is not in its allowlist is unambiguously
#      new, however large the global count has grown.
#
# THE ALLOWLISTS ARE GENERATED BY MEASUREMENT, NEVER HAND-WRITTEN:
#
#     ./scripts/check-deps.sh --update pochoir-core
#
# regenerates one from the current tree. Bumping an allowlist is therefore a
# deliberate, reproducible act that shows up as a diff. Do not edit these files
# by hand — ADR-0001 cites its own earlier wrong figure of 88 crates, copied
# from a probe of a configuration we do not use, as exactly why these numbers
# must come from a measurement in CI rather than from a document.
#
# Adding a dependency means, in the same commit: an ADR under docs/adr/, the
# regenerated allowlist, and a THRESHOLD bump if the global count moved.
#
# Allowlist file format: one crate name per line. Blank lines and lines
# starting with `#` are ignored, so a bump can be annotated. `--update` writes
# only sorted crate names, so an empty file means "zero third-party
# dependencies" — which is where both crates stand today.

set -eu

# --- Configuration -----------------------------------------------------------

# Global [[package]] budget. Measured, never copied from a document:
#
#     grep -c '^\[\[package\]\]' Cargo.lock
#
# 16 = the three workspace crates, plus the 11 third-party crates in the common
# path's runtime closure (see the allowlists), plus two entries the closure does
# not contain: `miniz_oxide` is locked twice (0.8 for `png`, 0.9 for `flate2`),
# and `zlib-rs` is locked as an optional `flate2` backend we do not enable. That
# gap between the lock file and the closure is exactly why check 2 exists.
#
# ADR-0001 predicted 14 for this step. The real figure was 15 with two crates,
# and is 16 since `pochoir-wasm` was added. That crate moved the figure by
# exactly one and took no third-party dependency of its own: its allowlist is
# byte-identical to `pochoir-core`'s, which is the measurement that says so.
# Trust the command above, never a figure copied from a document.
THRESHOLD=16

WASM_TARGET="wasm32-unknown-unknown"
ALLOWLIST_DIR="scripts/allowlist"

# Crates guarded per-crate, and the target each one's closure is measured for.
# `pochoir-core` is measured for wasm32 because that is the build the user
# downloads and the one ADR-0003's module split is about. `pochoir-cli` is
# measured for the host, because it is never built for wasm32 and a wasm32
# measurement of it would be a fiction. A `host` entry means "no --target flag".
# `pochoir-wasm` is measured for wasm32 for the same reason as the core: it *is*
# the module the browser downloads, and its closure is the core's plus whatever
# the bindings themselves pull in, which is meant to stay nothing.
GUARDED="pochoir-core:$WASM_TARGET
pochoir-cli:host
pochoir-wasm:$WASM_TARGET"

# --- Helpers -----------------------------------------------------------------

die() {
	echo "check-deps: $*" >&2
	exit 1
}

target_for() {
	echo "$GUARDED" | awk -F: -v want="$1" '$1 == want { print $2; exit }'
}

guarded_names() {
	echo "$GUARDED" | cut -d: -f1
}

# Package names of every crate in this workspace. These are excluded from the
# allowlists: an allowlist records third-party crates only, so that "empty"
# means "nothing we do not own", and so that adding an internal crate later is
# not mistaken for taking a dependency.
workspace_members() {
	for manifest in crates/*/Cargo.toml; do
		[ -f "$manifest" ] || continue
		sed -n 's/^name = "\(.*\)"$/\1/p' "$manifest" | head -1
	done
}

# The measured set: third-party crates in <crate>'s runtime dependency closure.
# `--edges normal` excludes dev- and build-dependencies on purpose. ADR-0001
# governs build-time tooling differently from anything that reaches the user's
# browser, and this check is about the latter; the global count above is what
# catches a dev-dependency.
measure() {
	crate="$1"
	target="$2"

	if [ "$target" = "host" ]; then
		set -- cargo tree -p "$crate" --edges normal --prefix none --format '{p}'
	else
		set -- cargo tree -p "$crate" --target "$target" --edges normal --prefix none --format '{p}'
	fi

	"$@" |
		awk 'NF { print $1 }' |
		grep -vxF -f "$MEMBERS_FILE" |
		sort -u
}

read_allowlist() {
	file="$1"
	[ -f "$file" ] || return 0
	sed -e 's/#.*//' -e 's/[[:space:]]*$//' "$file" | awk 'NF { print $1 }' | sort -u
}

# --- Mode: --update ----------------------------------------------------------

usage() {
	cat >&2 <<USAGE
Usage:
  ./scripts/check-deps.sh [Cargo.lock]        run every check
  ./scripts/check-deps.sh --update <crate>    regenerate one crate's allowlist
  ./scripts/check-deps.sh --update --all      regenerate every allowlist

Guarded crates: $(guarded_names | tr '\n' ' ')
USAGE
	exit 2
}

TMPDIR_RUN=$(mktemp -d)
trap 'rm -rf "$TMPDIR_RUN"' EXIT INT TERM
MEMBERS_FILE="$TMPDIR_RUN/members"
workspace_members | sort -u >"$MEMBERS_FILE"
[ -s "$MEMBERS_FILE" ] || die "found no workspace members under crates/. Run from the repository root."

update_one() {
	crate="$1"
	target=$(target_for "$crate")
	[ -n "$target" ] || die "'$crate' is not a guarded crate. Guarded: $(guarded_names | tr '\n' ' ')"

	mkdir -p "$ALLOWLIST_DIR"
	out="$ALLOWLIST_DIR/$crate.txt"
	measure "$crate" "$target" >"$out"
	n=$(awk 'END { print NR + 0 }' "$out")
	echo "check-deps: wrote $out - $n third-party crate(s) measured for target '$target'."
}

if [ "${1:-}" = "--update" ]; then
	shift
	[ $# -eq 1 ] || usage
	if [ "$1" = "--all" ]; then
		guarded_names | while read -r crate; do
			[ -n "$crate" ] && update_one "$crate"
		done
	else
		update_one "$1"
	fi
	echo "check-deps: review the diff and commit it with the ADR that justifies it."
	exit 0
fi

case "${1:-}" in
-h | --help) usage ;;
-*) usage ;;
esac

# --- Check 1: the global blunt alarm ----------------------------------------

LOCKFILE="${1:-Cargo.lock}"

if [ ! -f "$LOCKFILE" ]; then
	die "'$LOCKFILE' not found. Run 'make build' to generate it."
fi

count=$(grep -c '^\[\[package\]\]' "$LOCKFILE" || true)
: "${count:=0}"

if [ "$count" -gt "$THRESHOLD" ]; then
	echo "check-deps: FAIL (global count)" >&2
	echo "  $LOCKFILE contains $count packages, but the budget is $THRESHOLD." >&2
	echo "" >&2
	echo "  Packages currently locked:" >&2
	sed -n 's/^name = "\(.*\)"$/    - \1/p' "$LOCKFILE" >&2
	echo "" >&2
	echo "  A new dependency needs an ADR. Write one under docs/adr/ explaining" >&2
	echo "  why it cannot reasonably be built in-house, then raise THRESHOLD at" >&2
	echo "  the top of scripts/check-deps.sh in the same commit." >&2
	exit 1
fi

echo "check-deps: OK (global) - $count package(s) in $LOCKFILE, budget $THRESHOLD."

# --- Check 2: the per-crate allowlists --------------------------------------

failed=0

guarded_names | while read -r crate; do
	[ -n "$crate" ] || continue
	echo "$crate"
done >"$TMPDIR_RUN/crates"

while read -r crate; do
	target=$(target_for "$crate")
	allowfile="$ALLOWLIST_DIR/$crate.txt"

	if [ ! -f "$allowfile" ]; then
		echo "check-deps: FAIL (per-crate)" >&2
		echo "  $allowfile is missing. Generate it by measurement:" >&2
		echo "" >&2
		echo "      ./scripts/check-deps.sh --update $crate" >&2
		echo "" >&2
		failed=1
		continue
	fi

	measure "$crate" "$target" >"$TMPDIR_RUN/measured.$crate" || die "cargo tree failed for '$crate' (target '$target')."
	read_allowlist "$allowfile" >"$TMPDIR_RUN/allowed.$crate"

	added=$(comm -23 "$TMPDIR_RUN/measured.$crate" "$TMPDIR_RUN/allowed.$crate")
	removed=$(comm -13 "$TMPDIR_RUN/measured.$crate" "$TMPDIR_RUN/allowed.$crate")

	if [ -n "$added" ]; then
		echo "check-deps: FAIL (per-crate)" >&2
		echo "  $crate (target '$target') has dependencies that are not in $allowfile:" >&2
		echo "$added" | sed 's/^/    + /' >&2
		echo "" >&2
		echo "  A new dependency needs an ADR. Write one under docs/adr/ explaining" >&2
		echo "  why it cannot reasonably be built in-house, then regenerate the" >&2
		echo "  allowlist in the same commit:" >&2
		echo "" >&2
		echo "      ./scripts/check-deps.sh --update $crate" >&2
		echo "" >&2
		echo "  Do not edit the allowlist by hand: it is a measurement, and a" >&2
		echo "  hand-copied figure is how ADR-0001 ended up citing 88 crates." >&2
		failed=1
		continue
	fi

	if [ -n "$removed" ]; then
		echo "check-deps: FAIL (per-crate, stale allowlist)" >&2
		echo "  $allowfile lists crates that $crate no longer depends on:" >&2
		echo "$removed" | sed 's/^/    - /' >&2
		echo "" >&2
		echo "  Nothing new was pulled in, so this is bookkeeping rather than a" >&2
		echo "  policy breach - but an allowlist that does not match the measurement" >&2
		echo "  is a guard that has stopped guarding. Regenerate it:" >&2
		echo "" >&2
		echo "      ./scripts/check-deps.sh --update $crate" >&2
		echo "" >&2
		failed=1
		continue
	fi

	n=$(awk 'END { print NR + 0 }' "$TMPDIR_RUN/measured.$crate")
	echo "check-deps: OK (per-crate) - $crate matches $allowfile ($n third-party crate(s), target '$target')."
done <"$TMPDIR_RUN/crates" || failed=1

# The loop above reads from a file rather than a pipe, so it runs in this shell
# and `failed` survives it. Keep it that way: feeding the loop from a pipe would
# put it in a subshell and this check would silently always pass.
if [ "$failed" -ne 0 ]; then
	exit 1
fi

echo "check-deps: all checks passed."
