//! NFC normalisation, for the Latin ranges a French watermark needs.
//!
//! # Why this exists at all
//!
//! ADR-0002 Decision 3 requires the mark text to be normalised to **NFC**
//! before layout, and the reason is not pedantry. Text arriving from a macOS
//! filename, a clipboard paste or OCR is frequently NFD-decomposed: `é` is
//! stored as `e` followed by U+0301 COMBINING ACUTE ACCENT. Our renderer does
//! no shaping and no mark positioning — [ADR-0001] scopes it that way — so a
//! decomposed string would draw as a bare `e` followed by a stray accent
//! floating on the baseline. The target language is French, so `é è ç à ô û ï`
//! are ordinary input rather than an edge case.
//!
//! # Why it is a table and not a library
//!
//! [`COMPOSITIONS`] is 161 pairs covering Latin-1 Supplement and Latin
//! Extended-A. A full Unicode normaliser carries the whole Unicode Character
//! Database, handles Hangul algorithmically, and tracks canonical combining
//! classes for reordering — all of which we would ship to a browser to compose
//! `e` + acute.
//!
//! **The table is derived, not typed.** `scripts/gen-nfc-table.py` asks
//! Python's `unicodedata` for each character's canonical decomposition and
//! emits a pair only when recomposing it actually yields that character back,
//! which is what makes the Unicode composition exclusions handle themselves.
//! Regenerate it with:
//!
//! ```text
//! scripts/gen-nfc-table.py
//! ```
//!
//! and paste the output between the markers below. Do not hand-edit it: the
//! same rule as `scripts/allowlist/`, and for the same reason.
//!
//! # What this is not
//!
//! It is not a general NFC implementation and does not claim to be:
//!
//! - **No canonical reordering.** A base followed by two marks in
//!   non-canonical order will not compose. In the target range almost nothing
//!   takes two marks, and [`unsupported`] catches the leftover mark and turns
//!   it into an error the user can read.
//! - **No Hangul, no Indic, no decomposition of singletons.**
//! - **Already-composed text passes through untouched**, which is the common
//!   case and costs one scan.
//!
//! [ADR-0001]: ../../../../docs/adr/0001-stack-and-dependency-policy.md

