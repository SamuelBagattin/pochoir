/// Compose `text` to NFC, over the range above.
///
/// Runs to a fixed point, so a base carrying two composable marks — `A` +
/// diaeresis + macron — composes as far as the table allows rather than
/// stopping after one. In practice one pass is always enough for the target
/// range; the loop is there so that a regenerated table containing a chained
/// pair would just work.
#[must_use]
pub fn normalise(text: &str) -> String {
    let mut out: Vec<char> = text.chars().collect();
    // At most one mark is consumed per pass, so the number of passes is bounded
    // by the number of characters. The bound is on the loop, not on trust.
    for _ in 0..=out.len() {
        let mut composed = false;
        let mut next: Vec<char> = Vec::with_capacity(out.len());
        let mut index = 0;
        while index < out.len() {
            let current = out[index];
            let following = out.get(index + 1).copied();
            match following.and_then(|mark| compose(current, mark)) {
                Some(result) => {
                    next.push(result);
                    index += 2;
                    composed = true;
                }
                None => {
                    next.push(current);
                    index += 1;
                }
            }
        }
        out = next;
        if !composed {
            break;
        }
    }
    out.into_iter().collect()
}

/// The composition of `base` and `mark`, if the table has it.
#[must_use]
pub fn compose(base: char, mark: char) -> Option<char> {
    if !is_combining_mark(mark) {
        return None;
    }
    COMPOSITIONS
        .iter()
        .find(|&&(b, m, _)| b == base && m == mark)
        .map(|&(_, _, composed)| composed)
}

/// `true` if `character` is one of the combining marks this table composes.
#[must_use]
pub fn is_combining_mark(character: char) -> bool {
    COMBINING_MARKS.contains(&character)
}

/// Every character this table can produce.
///
/// Test-only, because its only caller is the test that asserts the table's outputs are all drawable by
/// the bundled font — two lists that have to agree, and a drifting pair would
/// put a `.notdef` box in the middle of somebody's watermark.
#[cfg(test)]
pub fn outputs() -> impl Iterator<Item = char> {
    COMPOSITIONS.iter().map(|&(_, _, composed)| composed)
}

/// Every character this table takes as a base. Test-only, as [`outputs`].
#[cfg(test)]
pub fn bases() -> impl Iterator<Item = char> {
    COMPOSITIONS.iter().map(|&(base, _, _)| base)
}

